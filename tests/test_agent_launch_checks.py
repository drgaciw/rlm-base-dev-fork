def _link_dir(link, target):
    """Create a directory link from `link` to `target` (a relative-path string,
    same shape as `Path.symlink_to`'s `target`).

    A real symlink needs admin rights or Developer Mode on Windows (WinError
    1314 otherwise); `link_skills.py --fix` sidesteps that in production by
    creating a directory junction there instead (`mklink /J`, no privilege
    required), which `analyzer._skill_link_resolves`/`_is_link_like` already
    accept alongside a real symlink (see `test_link_resolution_does_not_require_is_symlink`
    below). Mirror that here so these fixtures don't need Developer Mode either.
    """
    if os.name == "nt":
        abs_target = os.path.normpath(os.path.join(link.parent, target))
        proc = subprocess.run(["cmd", "/c", "mklink", "/J", str(link), abs_target],
                              capture_output=True, text=True, encoding="utf-8")
        if proc.returncode != 0:
            raise OSError(f"mklink /J {link} {abs_target} failed:\n{proc.stdout}{proc.stderr}")
    else:
        link.symlink_to(target, target_is_directory=True)


