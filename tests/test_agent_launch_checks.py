    def test_link_resolution_does_not_require_is_symlink(self):
        # A Windows directory junction (what `link_skills.py --fix` creates
        # there) reports `Path.is_symlink() == False` on every Python version
        # this repo supports, so the check must accept any entry that
        # resolves to the right target via realpath, not just a POSIX
        # symlink. This repo's real symlinks already exercise that realpath
        # path; assert directly that a valid link is accepted independent of
        # `is_symlink()`.
        p = self.root / ".agents/skills/cci-orchestration"
        target = self.root / ".cursor/skills/cci-orchestration"
        self.assertTrue(analyzer._skill_link_resolves(p, target))
        self.assertFalse(analyzer._skill_link_resolves(p, self.root / ".cursor/skills/missing"))

    def test_claude_md_regular_file_contract(self):
        p = self.root / "CLAUDE.md"
        # Not tracked as a regular file (e.g. still a symlink entry) fails the mode check.
        self.git("rm", "--cached", "CLAUDE.md")
        self.assertFalse(analyzer.check_native_skill_links(self.root).ok)
        self.git("add", "CLAUDE.md")
        self.assertTrue(analyzer.check_native_skill_links(self.root).ok)
        # Regular file, but wrong first line.
        p.write_text("AGENTS.md\n", encoding="utf-8")
        self.assertFalse(analyzer.check_native_skill_links(self.root).ok)
        # Regular file, correct import, but over the Claude-specific line budget.
        p.write_text("@AGENTS.md\n" + "\n".join(f"line {i}" for i in range(20)) + "\n", encoding="utf-8")
        self.assertFalse(analyzer.check_native_skill_links(self.root).ok)
        # Back to a valid file.
        p.write_text("@AGENTS.md\n\nClaude-specific note.\n", encoding="utf-8")
        self.assertTrue(analyzer.check_native_skill_links(self.root).ok)

