    def write(self, path, text):
        p = self.root / path
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
        return p

    def git(self, *args):
        return subprocess.run(["git", "-c", "core.fsmonitor=false", "-C", str(self.root), *args],
                              capture_output=True, text=True, check=True, encoding="utf-8")

    def _track_as_symlink(self, rel_path, target):
        """Force the git index entry at `rel_path` to record a symlink (mode
        120000) pointing at `target`, independent of what is really on disk
        there.

        On Windows, `rel_path` is a directory junction, not a real symlink
        (`_link_dir`) -- a junction is transparent to `git add`, which walks
        straight through it and adds the real files underneath at their own
        paths, not a mode-120000 blob at `rel_path` itself. A real checkout
        never hits that: the symlink blob was already committed (on a
        platform where it round-trips), and `link_skills.py --fix` only ever
        replaces the WORKING TREE (stub -> junction), never the index -- see
        `git update-index --skip-worktree` there. Reproduce that same index
        shape directly here instead of relying on `add` to produce it.
        """
        blob = subprocess.run(
            ["git", "-c", "core.fsmonitor=false", "-C", str(self.root), "hash-object", "-w", "--stdin"],
            input=target, capture_output=True, text=True, check=True, encoding="utf-8").stdout.strip()
        self.git("rm", "-q", "--cached", "-r", "--ignore-unmatch", rel_path)
        self.git("update-index", "--add", "--cacheinfo", f"120000,{blob},{rel_path}")

    def cli(self):
        # encoding="locale": the child prints console-decorated output (e.g. an
        # em-dash) through its own default stdout encoding -- the platform
        # locale/console codepage (cp1252 on this repo's Windows CI/dev boxes),
        # not necessarily UTF-8 -- so decoding here must follow the same
        # locale rather than assume UTF-8 and risk a UnicodeDecodeError.
        return subprocess.run([sys.executable, "-S", str(REPO / "scripts/ai/analyze_agent_tooling.py"),
                               "--repo-root", str(self.root), "check"], capture_output=True, text=True,
                              encoding="locale")

